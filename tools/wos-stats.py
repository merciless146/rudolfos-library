#!/usr/bin/env python3
"""Statistics of the WOS Galaxy Map's universe (Waste of Space), for Ember Reach's galaxy model.

Reads the map's packed data from a RudolfOS checkout (desktop/base_v24.html, GM_UNI) and writes only
distributions: how often each kind of star, planet, ring, atmosphere and resource occurs, how many planets a system
has, and the ranges of temperature and gravity per planet type. No names, coordinates or individual objects are
written, so nothing of the WOS world itself is copied into the game.

  python3 tools/wos-stats.py ../rudolfos/desktop/base_v24.html wip/emberreach/wos-stats.js
"""
import base64, collections, gzip, json, re, statistics as S, struct, sys

ST = ['Red', 'Orange', 'Yellow', 'Blue', 'Neutron', 'BlackHole', 'AsteroidField', 'RoguePlanet']
PT = ['Terra', 'EarthLike', 'Desert', 'Ocean', 'Tundra', 'Forest', 'Exotic', 'Barren', 'Gas', 'RobotDepot', 'RobotFactory']
RES = ['Iron', 'Copper', 'Coal', 'Lead', 'Titanium', 'Uranium', 'Jade', 'Gold', 'Diamond', 'Beryllium', 'Aluminum']

def read(path):
    raw = gzip.decompress(base64.b64decode(re.search(r"const GM_UNI='([^']+)'", open(path).read()).group(1)))
    o, stars, planets = 0, [], []
    def cs():
        nonlocal o
        e = raw.index(0, o); v = raw[o:e]; o = e + 1; return v
    while o < len(raw):
        x, y, z, w = struct.unpack_from('4b', raw, o); o += 4; k = raw[o]; o += 1
        if k == 0:
            stars.append({'sys': (x, y), 'type': ST[raw[o]], 'size': struct.unpack_from('<H', raw, o + 1)[0]}); o += 3
        else:
            t = PT[raw[o]]; o += 1; cs(); cs(); o += 6
            ma = raw[o]; o += 1; temp = struct.unpack_from('<h', raw, o)[0]; o += 2
            grav = struct.unpack_from('<f', raw, o)[0]; o += 4; rb = struct.unpack_from('<H', raw, o)[0]; o += 2
            planets.append({'sys': (x, y), 'type': t, 'atmo': bool((ma >> 3) & 1), 'locked': ((ma >> 4) & 1) == 0,
                            'ring': [None, 'Stone', 'Ice', None][(ma >> 5) & 3], 'temp': temp,
                            'grav': 196.2 if t == 'EarthLike' else grav, 'res': [RES[i] for i in range(11) if rb & (1 << i)]})
    return stars, planets

def main(src, out):
    stars, planets = read(src)
    C = collections.Counter
    systems = {s['sys'] for s in stars} | {p['sys'] for p in planets}
    per = C(C(p['sys'] for p in planets).values())
    types = {}
    for t in PT:
        ps = [p for p in planets if p['type'] == t]
        tt, gg = [p['temp'] for p in ps], [p['grav'] / 196.2 for p in ps]   # Roblox gravity: 196.2 is one Earth g
        types[t] = {'n': len(ps), 'share': round(len(ps) / len(planets), 4),
                    'temp': [min(tt), round(S.median(tt), 1), max(tt)], 'g': [round(min(gg), 3), round(S.median(gg), 3), round(max(gg), 3)],
                    'atmo': round(sum(p['atmo'] for p in ps) / len(ps), 3), 'locked': round(sum(p['locked'] for p in ps) / len(ps), 3),
                    'ring': round(sum(1 for p in ps if p['ring']) / len(ps), 3), 'iceRing': round(sum(1 for p in ps if p['ring'] == 'Ice') / max(1, sum(1 for p in ps if p['ring'])), 3),
                    'res': {r: round(sum(r in p['res'] for p in ps) / len(ps), 3) for r in RES}}
    out_d = {
        'source': 'WOS Galaxy Map (Waste of Space), statistics only',
        'systems': len(systems), 'stars': len(stars), 'planets': len(planets),
        'starMix': {k: round(v / len(stars), 4) for k, v in C(s['type'] for s in stars).most_common()},
        'starsPerSystem': {k: v for k, v in sorted(C(C(s['sys'] for s in stars).values()).items())},
        'planetsPerSystem': {k: per[k] for k in sorted(per)},
        'types': types}
    open(out, 'w').write('/* Generated by tools/wos-stats.py: statistics of the WOS Galaxy Map, no names or places. */\n'
                         'var WOS_STATS = ' + json.dumps(out_d, separators=(',', ':')) + ';\n'
                         "if (typeof module != 'undefined') module.exports = WOS_STATS;\n")
    print(out, len(systems), 'systems,', len(stars), 'stars,', len(planets), 'planets')

if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
